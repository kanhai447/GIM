CREATE TABLE audit_logs (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    event_id CHAR(36) NOT NULL,
    schema_version SMALLINT UNSIGNED NOT NULL,
    event_type VARCHAR(128) NOT NULL,
    service VARCHAR(64) NOT NULL,
    action VARCHAR(128) NOT NULL,
    user_id BIGINT UNSIGNED NULL,
    role TINYINT UNSIGNED NULL,
    resource_type VARCHAR(64) NOT NULL DEFAULT '',
    resource_id VARCHAR(128) NOT NULL DEFAULT '',
    request_id VARCHAR(128) NOT NULL DEFAULT '',
    trace_id VARCHAR(128) NOT NULL DEFAULT '',
    status VARCHAR(16) NOT NULL,
    error_code INT UNSIGNED NOT NULL DEFAULT 0,
    ip VARCHAR(64) NOT NULL DEFAULT '',
    method VARCHAR(16) NOT NULL DEFAULT '',
    path VARCHAR(512) NOT NULL DEFAULT '',
    occurred_at DATETIME(3) NOT NULL,
    metadata JSON NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY ux_audit_logs_event_id (event_id),
    KEY ix_audit_logs_occurred (occurred_at DESC, id DESC),
    KEY ix_audit_logs_user_occurred (user_id, occurred_at DESC, id DESC),
    KEY ix_audit_logs_type_occurred (event_type, occurred_at DESC, id DESC),
    KEY ix_audit_logs_service_occurred (service, occurred_at DESC, id DESC),
    KEY ix_audit_logs_request (request_id, occurred_at DESC, id DESC),
    CONSTRAINT ck_audit_logs_schema_version CHECK (schema_version > 0),
    CONSTRAINT ck_audit_logs_role CHECK (role IS NULL OR role IN (1, 2)),
    CONSTRAINT ck_audit_logs_status CHECK (status IN ('success', 'failed', 'denied')),
    CONSTRAINT ck_audit_logs_event_id CHECK (CHAR_LENGTH(event_id) = 36)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
